// Generates brand icon data from simple-icons (CC0 icon paths; brand marks belong to their owners).
// Output:
//   src/data/tool-icons.generated.ts  -> inline SVG paths used by <ToolIcon /> (themeable via currentColor)
//   public/icons/<id>.svg             -> standalone files, handy for docs/OG images
// Run: npm run icons
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as si from "simple-icons";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");

// tool id (used in src/data/tools.ts) -> simple-icons export name
const map = {
  n8n: "siN8n",
  whatsapp: "siWhatsapp",
  calcom: "siCaldotcom",
  gmail: "siGmail",
  googlesheets: "siGooglesheets",
  airtable: "siAirtable",
  supabase: "siSupabase",
  openai: "siOpenai",
  elevenlabs: "siElevenlabs",
  nextjs: "siNextdotjs",
  netlify: "siNetlify",
  googlemaps: "siGooglemaps",
  mcp: "siModelcontextprotocol",
};

const out = {};
mkdirSync(join(root, "public/icons"), { recursive: true });
for (const [id, key] of Object.entries(map)) {
  const icon = si[key];
  if (!icon) throw new Error(`simple-icons is missing ${key}`);
  out[id] = { title: icon.title, path: icon.path, hex: `#${icon.hex}` };
  writeFileSync(join(root, "public/icons", `${id}.svg`), icon.svg);
}

const file = `// AUTO-GENERATED by scripts/build-icons.mjs. Do not edit by hand.
export const brandIcons: Record<string, { title: string; path: string; hex: string }> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(join(root, "src/data/tool-icons.generated.ts"), file);
console.log(`Wrote ${Object.keys(out).length} icons.`);
